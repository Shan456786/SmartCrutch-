import type { ReactNode } from 'react';
import { FlaskConical, PlugZap, Usb } from 'lucide-react';
import { SERIAL_STATUS_LABEL, type SerialStatus } from '../state/LiveContext';

export function PageHeader({ title, subtitle, actions }: { title: string; subtitle?: string; actions?: ReactNode }) {
  return (
    <header className="page-header">
      <div>
        <h1>{title}</h1>
        {subtitle && <p className="page-subtitle">{subtitle}</p>}
      </div>
      {actions && <div className="page-actions">{actions}</div>}
    </header>
  );
}

export function Card({
  title,
  icon,
  actions,
  children,
  className = '',
  id,
}: {
  title?: string;
  icon?: ReactNode;
  actions?: ReactNode;
  children: ReactNode;
  className?: string;
  id?: string;
}) {
  return (
    <section className={`card ${className}`} id={id}>
      {(title || actions) && (
        <div className="card-head">
          {title && (
            <h2 className="card-title">
              {icon && <span className="card-icon">{icon}</span>}
              {title}
            </h2>
          )}
          {actions && <div className="card-actions">{actions}</div>}
        </div>
      )}
      {children}
    </section>
  );
}

export type BadgeTone = 'teal' | 'navy' | 'amber' | 'red' | 'gray' | 'green';

export function Badge({ tone = 'gray', children, dot }: { tone?: BadgeTone; children: ReactNode; dot?: boolean }) {
  return (
    <span className={`badge badge-${tone}`}>
      {dot && <span className="badge-dot" />}
      {children}
    </span>
  );
}

export function SimulatedTag() {
  return (
    <span className="sim-tag" title="These values are generated by the in-browser simulator, not by a real device.">
      <FlaskConical size={13} aria-hidden /> SIMULATED / DEMO DATA
    </span>
  );
}

export function HardwareTag() {
  return (
    <span className="hw-tag" title="Parsed from the ESP32 over USB serial (SmartCrutch+ JSON protocol v1). Calibration not verified.">
      <Usb size={13} aria-hidden /> LIVE HARDWARE DATA
    </span>
  );
}

/** Labels a reading with its true origin. */
export function SourceTag({ simulated }: { simulated: boolean }) {
  return simulated ? <SimulatedTag /> : <HardwareTag />;
}

const STATUS_TONE: Record<SerialStatus, BadgeTone> = {
  unsupported: 'red',
  disconnected: 'gray',
  connecting: 'amber',
  waiting: 'amber',
  live: 'green',
};

export function SerialStatusBadge({ status }: { status: SerialStatus }) {
  return (
    <Badge tone={STATUS_TONE[status]} dot>
      {SERIAL_STATUS_LABEL[status]}
    </Badge>
  );
}

const STATUS_TEXT: Record<SerialStatus, string> = {
  unsupported:
    'This browser does not support Web Serial. Use desktop Chrome or Edge, opened on http://localhost or HTTPS. No simulated values are shown in hardware mode.',
  disconnected: 'Connect the ESP32 by USB from Device & Settings. No simulated values are shown in hardware mode.',
  connecting: 'Opening the serial port…',
  waiting:
    'The serial port is open, but no valid SmartCrutch+ messages have arrived. The ESP32 must run firmware that prints the SmartCrutch+ JSON protocol — the current firmware only prints startup messages.',
  live: 'Receiving live data.',
};

export function NotConnected({ compact, status = 'disconnected' }: { compact?: boolean; status?: SerialStatus }) {
  return (
    <div className={`not-connected ${compact ? 'compact' : ''}`}>
      <PlugZap size={compact ? 18 : 28} aria-hidden />
      <div>
        <strong>{SERIAL_STATUS_LABEL[status]}</strong>
        {!compact && <p>{STATUS_TEXT[status]}</p>}
      </div>
    </div>
  );
}

